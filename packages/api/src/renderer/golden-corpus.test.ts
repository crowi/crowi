// ---------------------------------------------------------------------------
// The cases.
// ---------------------------------------------------------------------------

describe('golden corpus', () => {
  for (const [file, doc] of corpus) {
    describe(file, () => {
      for (const c of doc.cases) {
        it(c.name, async () => {
          // The stored-AST shape: produced by the real pipeline for
          // markdown cases, taken verbatim for synthetic ones.
          let stored: unknown;
          if (c.markdown !== undefined) {
            const { tree } = await runCore(c.markdown);
            stored = serializeMdast(tree);
            if (c.expectedAst !== undefined) {
              expect(stored).toEqual(c.expectedAst);
            }
          } else {
            stored = c.storedAst;
          }

          if (c.expectedEnvelope === undefined) return;

          // The corpus itself must be fully normalized — a real theme
          // color pinned by accident would make normalize() a no-op
          // mismatch here before it ever flakes on a shiki upgrade.
          expect(normalizeShikiColors(c.expectedEnvelope)).toEqual(c.expectedEnvelope);

          // The expected envelope must satisfy the strict wire schema
          // (placeholder colors included) — it is what the iOS strict
          // decoder consumes.
          expect(() => RenderedAstEnvelopeSchema.parse(c.expectedEnvelope)).not.toThrow();

          const actual = sanitizeAst(stored);
          // Presence-only verification of theme colors: the strict
          // schema requires `color` on every token style, but pins no
          // value — the placeholder comparison below is what the
          // corpus actually fixes.
          expect(() => RenderedAstEnvelopeSchema.parse(actual)).not.toThrow();
          expect(normalizeShikiColors(actual)).toEqual(c.expectedEnvelope);
        });
      }
    });
  }
});
