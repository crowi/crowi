/**
 * RFC-0023 / parent spec §13 (Phase 3) — the shared golden fixture
 * corpus driver, the api-side (producer) consumer of
 * `__fixtures__/golden-corpus/*.json`.
 *
 * Each corpus case pins one or both directions of the shipped
 * behaviour:
 *
 *   - `markdown` → `expectedAst`: the stored bare-Root shape
 *     (`runPipeline` with an EMPTY registry + `mode: 'save'` — the
 *     pipeline.test.ts `runCore` pattern, Mongo-independent; no
 *     dispatch runs, so plugin-generated byte strings never enter the
 *     corpus — `packages/e2e/tests/renderer-plugins.spec.ts` owns
 *     those) followed by `serializeMdast`.
 *   - (`storedAst` | `expectedAst`) → `expectedEnvelope`: the
 *     `X-Crowi-Ast-Version: 1` projection via `sanitizeAst`. Synthetic
 *     `storedAst` inputs cover the sidecar projections dispatch would
 *     normally produce (`crowiMath` / `crowiDiagram` / `crowiLinkCard`
 *     / `crowiPlaceholder`); `crowiCode` alone comes from real shiki
 *     output (a core transform, so it DOES run here).
 *
 * The CrowiKit XCTest consumer (listed in every file's `consumers`)
 * asserts the mirror image: its Swift sanitize-walker over the stored
 * shapes and its strict decoder over the envelopes. It is wired up in
 * Phase 4 — `apps/apple` lives on the `feature-ios-app/impl` branch,
 * not in this worktree.
 *
 * Shiki color normalization (documented in `code.json`'s
 * `normalization` field, mirrored by the Swift driver): token style
 * `color` / `bgColor` values are replaced with `"<color>"` on BOTH
 * sides before comparison — colors are shiki/theme-version-dependent
 * styling; token line structure, `content` boundaries and `fontStyle`
 * are the pinned contract. The corpus itself must already be fully
 * normalized (asserted below), so real theme colors can never be
 * pinned by accident.
 */

const silentLogger: PluginLogger = {
  debug: () => undefined,
  info: () => undefined,
  warn: () => undefined,
  error: () => undefined,
};

const loadDeps = createPipelineEsmDepsLoader();
const runCore = async (body: string) => {
  const reg = new RendererRegistryImpl();
  return runPipeline(body, reg, { mode: 'save', log: silentLogger, actor: { kind: 'system' } }, loadDeps);
};

