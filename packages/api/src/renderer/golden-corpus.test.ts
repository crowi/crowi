// ---------------------------------------------------------------------------
// Shiki color normalization (see the module doc comment).
// ---------------------------------------------------------------------------

const COLOR_PLACEHOLDER = '<color>';

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** A shiki token as the wire carries it: `content` + per-theme `light` / `dark` style objects. */
function isShikiToken(value: Record<string, unknown>): boolean {
  return typeof value.content === 'string' && isRecord(value.light) && isRecord(value.dark);
}

function normalizeStyle(style: unknown): unknown {
  if (!isRecord(style)) return style;
  const out: Record<string, unknown> = { ...style };
  if (typeof out.color === 'string') out.color = COLOR_PLACEHOLDER;
  if (typeof out.bgColor === 'string') out.bgColor = COLOR_PLACEHOLDER;
  return out;
}

function normalizeShikiColors(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(normalizeShikiColors);
  if (!isRecord(value)) return value;
  if (isShikiToken(value)) {
    return { ...value, light: normalizeStyle(value.light), dark: normalizeStyle(value.dark) };
  }
  const out: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value)) out[key] = normalizeShikiColors(entry);
  return out;
}

// ---------------------------------------------------------------------------
// Self-description — the corpus is a two-consumer contract and must say
// so itself (rule / why / consumers / normalization / exclusions).
// ---------------------------------------------------------------------------

describe('golden corpus self-description', () => {
  for (const [file, doc] of corpus) {
    describe(file, () => {
      it('describes its rule, rationale and normalization', () => {
        expect(doc.rule.length).toBeGreaterThan(0);
        expect(doc.why.length).toBeGreaterThan(0);
        expect(doc.normalization.length).toBeGreaterThan(0);
      });

      it('lists both consumers (this driver + the CrowiKit XCTest mirror)', () => {
        expect(doc.consumers).toContain('packages/api/src/renderer/golden-corpus.test.ts');
        expect(doc.consumers.some((c) => c.startsWith('apps/apple/CrowiKit/Tests/'))).toBe(true);
        expect(doc.consumerContract.length).toBeGreaterThan(0);
      });

      it('records why dispatch-generated byte strings are excluded', () => {
        expect(doc.exclusions).toContain('renderer-plugins.spec.ts');
      });

      it('contains every AC-mandated case', () => {
        const names = doc.cases.map((c) => c.name);
        for (const required of REQUIRED_CASES[file]) {
          expect(names).toContain(required);
        }
        // Case names double as test ids — they must be unique.
        expect(new Set(names).size).toBe(names.length);
      });

      it('every case is self-describing and pins at least one direction', () => {
        for (const c of doc.cases) {
          expect(c.name.length).toBeGreaterThan(0);
          expect(c.why.length).toBeGreaterThan(0);
          const hasSource = c.markdown !== undefined || c.storedAst !== undefined;
          const hasExpectation = c.expectedAst !== undefined || c.expectedEnvelope !== undefined;
          expect(hasSource).toBe(true);
          expect(hasExpectation).toBe(true);
          // A synthetic case has nothing to produce the stored shape from,
          // so it must pin the projection.
          if (c.markdown === undefined) expect(c.expectedEnvelope).toBeDefined();
        }
      });
    });
  }
});

